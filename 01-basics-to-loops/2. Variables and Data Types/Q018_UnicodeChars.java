// Print characters using Unicode escape sequences such as \u0041.

public class Q018_UnicodeChars {
    public static void main(String[] args) {

        System.out.println("\u0041");
        System.out.println("\u0042");
        System.out.println("\u0043");
        System.out.println("\u0061");
        System.out.println("\u0024");
        System.out.println("\u0040");
    }
}

// Output
// A
// B
// C
// a
// $
// @