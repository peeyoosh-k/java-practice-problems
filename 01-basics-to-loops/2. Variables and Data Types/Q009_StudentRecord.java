// Declare variables for roll number, name, marks, and grade of a 
// student and print the complete record.

public class Q009_StudentRecord {
    public static void main(String[] args) {

        int rollNum = 24;
        String name = "Ankush";
        double marks = 77.8;
        char grade = 'B';
        
        System.out.println("Roll Number = " + rollNum);
        System.out.println("Name = " + name);
        System.out.println("Marks = " + marks);
        System.out.println("Grade = " + grade);
    }
}

// Output
// Roll Number = 24
// Name = Ankush
// Marks = 77.8
// Grade = B