// Declare very large and very small numbers using scientific notation (e) 
// and print them.

public class Q015_ScientificNotation {
    public static void main(String[] args) {
        
        double large = 1.5e10;
        double small = 2.5e-8;

        System.out.println("Large = " + large);
        System.out.println("Small = " + small);

    }
}

// Output 
// Large = 1.5E10
// Small = 2.5E-8