// Print a four-line poem-style message using a single 
// println statement and the \n escape sequence.

public class Q004_MultiLinePrint {
    public static void main(String[] args) {
        
        System.out.println("Small walls of brackets, a roof held high,\na door of pipes beneath the sky.\nNo bricks, no wood, just symbols neat,\nand println makes the home complete.");
    }
}

// Output 
// Small walls of brackets, a roof held high,
// a door of pipes beneath the sky.
// No bricks, no wood, just symbols neat,
// and println makes the home complete.